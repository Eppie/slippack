#!/usr/bin/env python3
"""Build the frozen Gecko v1 dictionary from a small, explicit replay sample.

Normal builds use the checked-in header, never local replays. Existing format
IDs are immutable: a different dictionary must receive a new ID and retain v1.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path


def sha(data):
    return hashlib.sha256(data).hexdigest()


def payloads(data):
    if len(data) < 17 or data[:11] != b'{U\x03raw[$U#l' or data[15] != 0x35:
        return []
    length = data[16]
    if length < 1 or (length - 1) % 3 or 16 + length > len(data):
        return []
    table = {data[i]: int.from_bytes(data[i+1:i+3], 'big')
             for i in range(17, 16 + length, 3)}
    declared = int.from_bytes(data[11:15], 'big')
    end = 15 + declared if declared and 15 + declared <= len(data) else len(data)
    pos, pending, result = 16 + length, bytearray(), []
    while pos < end:
        cmd = data[pos]
        size = table.get(cmd)
        if size is None or pos + 1 + size > end:
            break
        record = data[pos+1:pos+1+size]
        if cmd == 0x3d:
            result.append(record)
        elif cmd == 0x10:
            if size != 516 or record[514] != 0x3d or record[515] > 1:
                return []
            actual = int.from_bytes(record[512:514], 'big')
            if actual > 512:
                return []
            pending.extend(record[:actual])
            if record[515]:
                result.append(bytes(pending))
                pending.clear()
        pos += size + 1
    return result


def entries(data):
    pos, result = 0, []
    while pos < len(data):
        if pos + 8 > len(data):
            return []
        kind = data[pos] & 0xfe
        value = int.from_bytes(data[pos+4:pos+8], 'big')
        # Only known layouts enter the training dictionary. Runtime matching
        # is byte based and never interprets or executes embedded code.
        if kind in (0xc0, 0xc2):
            length = 8 + value * 8
        elif kind == 6:
            length = 8 + ((value + 7) & ~7)
        elif kind == 8:
            length = 16
        elif kind in (2, 4):
            length = 8
        else:
            return []
        if pos + length > len(data):
            return []
        result.append(data[pos:pos+length])
        pos += length
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, required=True)
    parser.add_argument('--inventory', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--provenance', type=Path, required=True)
    args = parser.parse_args()
    inventory = json.loads(args.inventory.read_text())['inputs']
    by_hash = {row['sha256']: row for row in inventory}
    paths = [Path(p) for p in args.manifest.read_text().splitlines() if p]
    sources = defaultdict(list)
    for path in paths:
        data = path.read_bytes()
        key = sha(data)
        row = by_hash[key]
        assert len(data) == row['bytes']
        sources[row['source']].append((key, path))
    excluded = sorted(s for s in sources
                      if int.from_bytes(hashlib.sha256(s.encode()).digest()[:4], 'big') % 4 == 2)
    selected, uses, blocks = [], defaultdict(set), {}
    for source in sorted(sources):
        if source in excluded:
            continue
        # The choice is independent of compression outcomes and payload hashes.
        for key, path in sorted(sources[source])[:8]:
            data = path.read_bytes()
            assert sha(data) == key
            selected.append(dict(source=source, sha256=key, bytes=len(data)))
            for payload in payloads(data):
                for block in entries(payload):
                    digest = sha(block)
                    blocks[digest] = block
                    uses[digest].add(key)
    blob, descriptions = bytearray(), []
    for key in sorted(blocks):
        if len(uses[key]) < 2:
            continue
        block = blocks[key]
        descriptions.append(dict(sha256=key, offset=len(blob), bytes=len(block),
                                 training_replays=len(uses[key])))
        blob.extend(block)
    header = ['// Generated by tools/build_gecko_dictionary.py; immutable format ID 1.',
              '// clang-format off', '#pragma once',
              'namespace slippack {', 'alignas(64) static constexpr uint8_t kGeckoV1[] = {']
    header.extend('  ' + ','.join(f'0x{b:02x}' for b in blob[i:i+20]) + ','
                  for i in range(0, len(blob), 20))
    header.extend(['};', '} // namespace slippack', '// clang-format on', ''])
    generated = '\n'.join(header).encode()
    if args.header.exists() and args.header.read_bytes() != generated:
        raise ValueError('refusing to replace a frozen dictionary; choose a new format ID')
    args.header.write_bytes(generated)
    report = dict(format_id=1, bytes=len(blob), sha256=sha(blob),
                  header_sha256=sha(generated), training_inputs=selected,
                  selection='First 8 replay SHA-256s per source, excluding source SHA-256 '
                            'first big-endian u32 modulo 4 == 2; entries in >=2 training replays.',
                  excluded_sources=excluded, entries=descriptions,
                  inventory_sha256=sha(args.inventory.read_bytes()),
                  scope='Development sample only. Excluded sources are a dictionary-generalization '
                        'check, not a fresh holdout for the codec as a whole.')
    args.provenance.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k: v for k, v in report.items()
                      if k not in ('training_inputs', 'entries')}, indent=2))
    print(f'{len(selected)} training replays, {len(descriptions)} dictionary entries')


if __name__ == '__main__':
    main()
